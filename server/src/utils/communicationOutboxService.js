/**
 * Processes queued outbox messages, enforcing quiet hours, retry backoff, and idempotent delivery.
 */
export async function processOutboxQueue(companyId) {
  const now = new Date();
  const inQuietHours = isWithinQuietHours(now);

  const pending = await OutboxMessage.find({
    companyId,
    status: { $in: ["queued", "quiet_hours_delayed", "failed"] },
    nextAttemptAt: { $lte: now },
    attempts: { $lt: 4 }
  }).sort({ createdAt: 1 }).limit(25);

  const results = [];

  for (const msg of pending) {
    // Critical emergencies bypass quiet hours; all others are held until 08:00 AM IST
    if (inQuietHours && msg.severity !== "critical") {
      const nextDispatch = getNextQuietHoursEnd(now);
      await OutboxMessage.updateOne(
        { companyId, id: msg.id },
        {
          $set: {
            status: "quiet_hours_delayed",
            nextAttemptAt: nextDispatch,
            lastAttemptAt: now
          }
        }
      );
      results.push({ id: msg.id, status: "quiet_hours_delayed", nextAttemptAt: nextDispatch });
      continue;
    }

    const { status, deliveryReceipt, error } = await dispatchMessageChannel(msg);
    const newAttempts = (msg.attempts || 0) + 1;

    const updateDoc = {
      attempts: newAttempts,
      lastAttemptAt: now,
      deliveryReceipt: deliveryReceipt || undefined,
      lastError: error || null
    };

    if (status === "sent") {
      updateDoc.status = "sent";
      updateDoc.deliveredAt = now;
    } else {
      updateDoc.status = "failed";
      // Exponential backoff: 2 min, 8 min, 32 min
      const backoffMs = Math.pow(4, newAttempts) * 30 * 1000;
      updateDoc.nextAttemptAt = new Date(now.getTime() + backoffMs);
    }

    await OutboxMessage.updateOne({ companyId, id: msg.id }, { $set: updateDoc });
    results.push({ id: msg.id, status, error });
  }

  return { processedCount: results.length, inQuietHours, results };
}

/**
 * Queues a notification message into the transactional outbox.
 */
export async function queueNotificationMessage({
  companyId,
  channel,
  recipient,
  subject = null,
  body,
  severity = "medium",
  caseId = null,
  idempotencyKey = null
}) {
  const now = new Date();
  const messageId = `MSG-${channel.toUpperCase()}-${Date.now()}-${crypto.randomBytes(4).toString("hex")}`;
  const key = idempotencyKey || `${companyId}:${channel}:${recipient}:${crypto.createHash("md5").update(body).digest("hex")}`;

  const inQuietHours = isWithinQuietHours(now);
  const initialStatus = inQuietHours && severity !== "critical" ? "quiet_hours_delayed" : "queued";
  const nextAttemptAt = inQuietHours && severity !== "critical" ? getNextQuietHoursEnd(now) : now;

  const doc = await OutboxMessage.findOneAndUpdate(
    { companyId, idempotencyKey: key },
    {
      $setOnInsert: {
        companyId,
        id: messageId,
        messageId,
        channel,
        recipient,
        subject,
        body,
        severity,
        caseId,
        status: initialStatus,
        idempotencyKey: key,
        attempts: 0,
        maxAttempts: 3,
        scheduledAt: now,
        nextAttemptAt,
        deliveredAt: null,
        lastError: null,
        createdAt: now
      }
    },
    { upsert: true, returnDocument: "after" }
  );

  return doc;
}

